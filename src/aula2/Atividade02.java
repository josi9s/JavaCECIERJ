package aula2;

public class Atividade02 {
    public static void main(String[] args) {
        int num1 = 1;
        int num2 = 2;
        int num3 = 3;

        System.out.println("A soma dos números é: " + (num1 + num2 + num3));
        System.out.println("A média dos números é: " + (num1 + num2 + num3) / 3);
    }
}